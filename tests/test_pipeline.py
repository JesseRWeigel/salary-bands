"""The whole pipeline over fixtures/fixture.xlsx, against hand-computed ground truth.

Nothing here compares the code to itself. Every expected value comes from
fixtures/expected.json, which was worked out by hand and is not generated by any code in
this repository.
"""

import unittest

from bands import aggregate

from .support import EXPECTED, FIXTURE, FIXTURE_MIN_N


def build():
    aggregate.MIN_N_EMPLOYER = aggregate.MIN_N_METRO = aggregate.MIN_N_CELL = FIXTURE_MIN_N
    return aggregate.build([FIXTURE], [{"file": "fixture.xlsx"}])


class TestRowSelection(unittest.TestCase):
    def setUp(self):
        self.trace = []
        self.rows, self.meta = aggregate.load([FIXTURE], trace=self.trace)

    def test_counts(self):
        self.assertEqual(self.meta["rows_read"], EXPECTED["rows_read"])
        self.assertEqual(self.meta["rows_kept"], EXPECTED["rows_kept"])

    def test_every_row_reaches_the_outcome_it_should(self):
        got = {}
        dups = 0
        for case, outcome in self.trace:
            if case in got:
                self.assertEqual(outcome, "duplicate_case_number", case)
                dups += 1
                continue
            got[case] = outcome
        self.assertEqual(got, EXPECTED["trace"])
        self.assertEqual(dups, EXPECTED["duplicate_case_rejections"])

    def test_filter_counts(self):
        self.assertEqual(self.meta["filters"], EXPECTED["filters"])

    def test_wage_conversion_outcomes(self):
        self.assertEqual(self.meta["wage_conversion_outcomes"],
                         EXPECTED["wage_conversion_outcomes"])
        self.assertEqual(self.meta["wage_unit_counts_after_status_filters"],
                         EXPECTED["wage_unit_counts_after_status_filters"])

    def test_status_and_visa_counts(self):
        self.assertEqual(self.meta["case_status_of_h1b_rows"],
                         EXPECTED["case_status_of_h1b_rows"])
        self.assertEqual(self.meta["visa_class_of_all_rows"],
                         EXPECTED["visa_class_of_all_rows"])

    def test_each_kept_row_carries_the_right_values(self):
        got = {r.case: {"annual": int(r.annual), "unit": r.unit, "family": r.family,
                        "level": r.level, "employer": r.employer, "metro": r.metro}
               for r in self.rows}
        self.assertEqual(got, EXPECTED["kept_rows"])


